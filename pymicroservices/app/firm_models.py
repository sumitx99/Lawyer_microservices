"""Firm, people, access and audit tables. Alembic migrations in alembic/versions are generated
from this file and models.py (the RAG tables) and committed; nothing is autogenerated at boot.

Two user populations, as in the SLR backend: `admins` (Admin console) and
`iam_users` (IAM console). Every business row carries `firm_id` (one deployment,
many firms)."""
import uuid
from datetime import datetime, timezone

from sqlalchemy import (JSON, Boolean, CheckConstraint, DateTime, ForeignKey, Integer,
                        String, Text, UniqueConstraint)
from sqlalchemy.orm import Mapped, mapped_column

from pymicroservices.app.utilities.firm_db import FirmBase


def new_id() -> str:
    return str(uuid.uuid4())


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


TZ = DateTime(timezone=True)


class Firm(FirmBase):
    __tablename__ = "firms"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    name: Mapped[str] = mapped_column(String(200))
    slug: Mapped[str] = mapped_column(String(80), unique=True)
    require_mfa: Mapped[bool] = mapped_column(Boolean, default=True)
    allowed_email_domains: Mapped[list] = mapped_column(JSON, default=list)
    # Each firm is a WorkOS Organization, so a firm can turn on its own SSO later.
    workos_organization_id: Mapped[str | None] = mapped_column(String(100), unique=True)
    created_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)


class Admin(FirmBase):
    """Admin console user. Full access to everything inside their firm."""
    __tablename__ = "admins"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    firm_id: Mapped[str] = mapped_column(ForeignKey("firms.id", ondelete="CASCADE"), index=True)
    provider_subject: Mapped[str | None] = mapped_column(String(200), unique=True)
    email: Mapped[str] = mapped_column(String(320), unique=True)
    name: Mapped[str] = mapped_column(String(200))
    admin_role: Mapped[str] = mapped_column(String(30), default="admin")  # room for super_admin later
    status: Mapped[str] = mapped_column(String(20), default="invited")  # invited | active | deactivated
    created_by: Mapped[str | None] = mapped_column(ForeignKey("admins.id", ondelete="SET NULL"))
    last_login_at: Mapped[datetime | None] = mapped_column(TZ)
    created_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)


class IamUser(FirmBase):
    """IAM console user. What they can do = firm role + matter roles."""
    __tablename__ = "iam_users"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    firm_id: Mapped[str] = mapped_column(ForeignKey("firms.id", ondelete="CASCADE"), index=True)
    provider_subject: Mapped[str | None] = mapped_column(String(200), unique=True)
    email: Mapped[str] = mapped_column(String(320), unique=True)
    name: Mapped[str] = mapped_column(String(200))
    firm_role: Mapped[str] = mapped_column(String(40), default="PARALEGAL")
    status: Mapped[str] = mapped_column(String(20), default="invited")
    created_by_admin: Mapped[str | None] = mapped_column(ForeignKey("admins.id", ondelete="SET NULL"))
    last_login_at: Mapped[datetime | None] = mapped_column(TZ)
    created_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(TZ, default=utcnow, onupdate=utcnow)


class AuthSession(FirmBase):
    """Server-side session. The cookie holds a random token; only its hash is stored."""
    __tablename__ = "sessions"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    console: Mapped[str] = mapped_column(String(10))  # admin | iam
    principal_id: Mapped[str] = mapped_column(String(36), index=True)
    firm_id: Mapped[str] = mapped_column(ForeignKey("firms.id", ondelete="CASCADE"))
    refresh_token_enc: Mapped[str | None] = mapped_column(Text)
    provider_session_id: Mapped[str | None] = mapped_column(String(100))  # WorkOS `sid`, for hosted logout
    ip: Mapped[str | None] = mapped_column(String(64))
    user_agent: Mapped[str | None] = mapped_column(String(400))
    created_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)
    last_seen_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)
    last_verified_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)
    expires_at: Mapped[datetime] = mapped_column(TZ)
    revoked_at: Mapped[datetime | None] = mapped_column(TZ)


class PermissionSet(FirmBase):
    """One row per built-in role, synced from app/security/permissions.py at startup."""
