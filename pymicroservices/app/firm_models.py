class TeamMember(FirmBase):
    __tablename__ = "team_members"
    team_id: Mapped[str] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"), primary_key=True)
    user_id: Mapped[str] = mapped_column(ForeignKey("iam_users.id", ondelete="CASCADE"), primary_key=True, index=True)
    added_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)


class Matter(FirmBase):
    """A case or engagement (SLR's project / data_fabric)."""
    __tablename__ = "matters"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    firm_id: Mapped[str] = mapped_column(ForeignKey("firms.id", ondelete="CASCADE"), index=True)
    number: Mapped[str] = mapped_column(String(40))
    name: Mapped[str] = mapped_column(String(200))
    client_name: Mapped[str] = mapped_column(String(200))
    practice_area: Mapped[str] = mapped_column(String(80), default="Personal injury")
    status: Mapped[str] = mapped_column(String(20), default="open")  # open | closed
    created_by: Mapped[str | None] = mapped_column(ForeignKey("iam_users.id", ondelete="SET NULL"))
    created_by_admin: Mapped[str | None] = mapped_column(ForeignKey("admins.id", ondelete="SET NULL"))
    opened_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)
    closed_at: Mapped[datetime | None] = mapped_column(TZ)
    deleted_at: Mapped[datetime | None] = mapped_column(TZ)
    __table_args__ = (UniqueConstraint("firm_id", "number"),)


class MatterMember(FirmBase):
    """ACL entry: a user or team holds a matter role. role=blocked is an ethical wall."""
    __tablename__ = "matter_members"
    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    matter_id: Mapped[str] = mapped_column(ForeignKey("matters.id", ondelete="CASCADE"), index=True)
    principal_type: Mapped[str] = mapped_column(String(10))  # user | team
    principal_id: Mapped[str] = mapped_column(String(36), index=True)
    role: Mapped[str] = mapped_column(String(10))  # LEAD | EDITOR | VIEWER | BLOCKED
    wall_reason: Mapped[str | None] = mapped_column(String(500))
    assigned_by: Mapped[str | None] = mapped_column(String(36))
    assigned_at: Mapped[datetime] = mapped_column(TZ, default=utcnow)
    __table_args__ = (
        UniqueConstraint("matter_id", "principal_type", "principal_id"),
        CheckConstraint("role <> 'BLOCKED' OR principal_type = 'user'", name="wall_users_only"),
    )


